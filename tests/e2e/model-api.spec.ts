import { test, expect } from '@playwright/test';

test('SYNTHETIC API settings, hidden key, independent probe, analysis and manual fallback', async ({ page, request, context }) => {
  const api = 'http://127.0.0.1:18765'; const headers = { Authorization: 'Bearer e2e-isolated-session' };
  await page.goto('/settings?api=' + encodeURIComponent(api) + '#token=e2e-isolated-session');
  const panel = page.getByRole('region', { name: '模型 API 设置' });
  await expect(panel).toBeVisible();
  await expect(panel.getByRole('button', { name: '启动合成生成测试' })).toBeDisabled();
  await panel.getByLabel('启用 API 分析入口').check();
  await panel.getByRole('button', { name: '保存模型配置' }).click();
  const key = panel.locator('input[type="password"]');
  await key.fill('SYNTHETIC-browser-key');
  await panel.getByRole('button', { name: '保存到 Windows 凭据' }).click();
  await expect(key).toHaveValue('');
  await expect(panel.getByText('密钥状态：已配置')).toBeVisible();
  expect(await page.evaluate(() => Object.values(localStorage).join('') + Object.values(sessionStorage).join(''))).not.toContain('SYNTHETIC-browser-key');
  await panel.getByRole('button', { name: '鉴权并读取模型列表' }).click();
  await expect(panel.getByText(/模型列表：查询成功/)).toBeVisible();
  await expect(panel.getByText('字符保真待验证')).toBeVisible();
  await panel.getByRole('button', { name: '按需查询余额' }).click();
  await expect(panel.getByText(/最近成功余额：18 SYNTHETIC-CREDIT/)).toBeVisible();
  await panel.getByLabel('我主动启动这次可能收费的合成测试').check();
  await panel.getByRole('button', { name: '启动合成生成测试' }).click();
  await expect(panel.getByRole('region', { name: '模型调用状态' }).getByText('处理完成', { exact: true })).toBeVisible();
  await expect(panel.getByText('字符保真测试已通过', { exact: true })).toBeVisible();
  await page.screenshot({ path: `${process.env.XAU_NEXT_E2E_SCREENSHOTS ?? 'test-results'}/model-settings-desktop.png`, fullPage: true });
  await page.goto('/analysis');
  await expect(page.getByRole('button', { name: '用 API 生成新分析', exact: true })).toBeEnabled();
  const creating = page.waitForRequest(item => item.url() === api + '/v1/analysis/requests' && item.method() === 'POST');
  await page.getByRole('button', { name: '用 API 生成新分析', exact: true }).click();
  expect((await creating).postDataJSON()).not.toHaveProperty('horizon_minutes');
  const call = page.getByRole('region', { name: '模型调用状态' });
  await expect(call.getByText('处理完成', { exact: true })).toBeVisible({ timeout: 15000 });
  await expect(call.getByText(/回答校验：通过 · 候选 0 个/)).toBeVisible();
  await expect(page.getByRole('button', { name: '复制完整分析包' })).toBeEnabled();
  await expect(page.getByLabel('结构化回答原文')).toBeVisible();
  const reqId = new URL(page.url()).searchParams.get('request')!;
  const frozen = await (await request.get(`${api}/v1/analysis/requests/${reqId}`, { headers })).json();
  expect(frozen.horizon_minutes).toEqual([30, 60, 180, 360, 720]);
  const saved = await (await request.get(`${api}/v1/analysis/requests/${reqId}/model-call`, { headers })).json();
  expect(saved.version_id).toBeTruthy(); expect(saved.call.state).toBe('succeeded');
  const version = await (await request.get(`${api}/v1/forecasts/${frozen.forecast_id}/versions/${saved.version_id}`, { headers })).json();
  expect(version.answer.horizons.map((item: { horizon_minutes: number }) => item.horizon_minutes)).toEqual([30, 60, 180, 360, 720]);
  await call.getByRole('button', { name: '查看模型原响应' }).click();
  await expect(call.getByText('完整原响应与提取回答')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('region', { name: '模型调用状态' }).getByText('处理完成', { exact: true })).toBeVisible();
  const again = await (await request.get(`${api}/v1/analysis/requests/${reqId}/model-call`, { headers })).json();
  expect(again.call.call_id).toBe(saved.call.call_id); expect(again.version_id).toBe(saved.version_id);
  await page.screenshot({ path: `${process.env.XAU_NEXT_E2E_SCREENSHOTS ?? 'test-results'}/model-analysis-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `${process.env.XAU_NEXT_E2E_SCREENSHOTS ?? 'test-results'}/model-analysis-mobile.png`, fullPage: true });
  await page.close();
  const reopened = await context.newPage();
  await reopened.goto(`/analysis?request=${reqId}&api=${encodeURIComponent(api)}#token=e2e-isolated-session`);
  await expect(reopened.getByRole('region', { name: '模型调用状态' }).getByText('处理完成', { exact: true })).toBeVisible();
});

test('SYNTHETIC invalid answer shows field errors and preserves failed import', async ({ page, request }) => {
  const api = 'http://127.0.0.1:18765'; const auth = { Authorization: 'Bearer e2e-isolated-session' };
  const headers = () => ({ ...auth, 'Idempotency-Key': crypto.randomUUID() });
  const config = await (await request.get(api + '/v1/model/settings', { headers: auth })).json();
  const saved = await (await request.put(api + '/v1/model/settings', { headers: headers(), data: { expected_revision: config.revision, values: { ...config.values, enabled: true, model_id: 'SYNTHETIC-invalid-output' } } })).json();
  expect((await request.post(api + '/v1/model/credential', { headers: headers(), data: { expected_revision: saved.revision, key: 'SYNTHETIC-browser-key' } })).ok()).toBeTruthy();
  await page.goto('/settings?api=' + encodeURIComponent(api) + '#token=e2e-isolated-session');
  const settings = page.getByRole('region', { name: '模型 API 设置' });
  await settings.getByLabel('我主动启动这次可能收费的合成测试').check();
  await settings.getByRole('button', { name: '启动合成生成测试' }).click();
  await expect(settings.getByText('字符保真测试已通过', { exact: true })).toBeVisible();
  await page.goto('/analysis');
  await page.getByRole('button', { name: '用 API 生成新分析', exact: true }).click();
  const call = page.getByRole('region', { name: '模型调用状态' });
  await expect(call.getByText('回答字段错误（3 项）')).toBeVisible({ timeout: 15000 });
  await expect(call.getByText('/market_cutoff', { exact: true })).toBeVisible();
  await expect(call.getByText(/missing_conditions.*required/)).toHaveCount(2);
  await expect(call.getByText('回答未导入，原文已保留')).toBeVisible();
  const reqId = new URL(page.url()).searchParams.get('request')!;
  const record = await (await request.get(`${api}/v1/analysis/requests/${reqId}/model-call`, { headers: auth })).json();
  expect(record.version_id).toBeNull(); expect(record.call.error_code).toBe('SCHEMA_INVALID');
  await page.screenshot({ path: `${process.env.XAU_NEXT_E2E_SCREENSHOTS ?? 'test-results'}/model-field-errors-desktop.png`, fullPage: true });
  await page.reload();
  await expect(page.getByRole('region', { name: '模型调用状态' }).getByText('回答字段错误（3 项）')).toBeVisible();
  const after = await (await request.get(`${api}/v1/analysis/requests/${reqId}/model-call`, { headers: auth })).json();
  expect(after.call.call_id).toBe(record.call.call_id); expect(after.version_id).toBeNull();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `${process.env.XAU_NEXT_E2E_SCREENSHOTS ?? 'test-results'}/model-field-errors-mobile.png`, fullPage: true });
});
